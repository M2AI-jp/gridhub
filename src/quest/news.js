// ユーザーの言葉:「作ってる製品に関連ニュースが流れる」。開発一般のコツではなく、作っている製品の分野の話題にする。

/** GM のプロンプトに入れる決まり（1行ずつ。先頭の「- 」は付けない） */
export const NEWS_GUIDE = [
  '`quest.news`（瓦版の話題）に、**作っている製品の分野**の話題を3〜8件（各120字以内の文字列の配列）書きます。盤面の道の余白（瓦版）に流れ、エージェントと人が「何を、誰のために作っているのか」を思い出すためのものです。',
  '書くのは、その製品を使う人・使われ方・その分野でよくある機能や考え方です。例（メモアプリなら）「メモアプリでは、全文検索より先にタグで絞り込む使い方がよく見られる」「オフラインで書いて、つながったら同期する、という考え方がある」「メモの一覧は、新しく書いた順に並べる作りが多い」。',
  '開発の進め方のコツ（テストを先に書く・こまめにコミットする・レビュー・CI など）は書きません。どの製品にも当てはまるので、瓦版の話題になりません。ただし、作っている製品そのものが開発の道具なら、その道具の使われ方は書いてかまいません。',
  '作り話を事実のように書きません。実在の会社名・製品名・人名、数字（%・人数・金額）、日付、「発表した」「調査によると」のような出来事は書かず、「〜という考え方がある」「〜がよく使われる」「〜という使い方が多い」のような一般的な言い方にします。',
];

/** 開発の進め方のコツに見える言葉（製品が開発の道具でなければ、瓦版の話題にしない） */
const PROCESS = /テスト駆動|テストを先に|TDD|コミット|プルリク|pull request|コードレビュー|リファクタ|\bCI\b|継続的インテグレーション|デプロイ|ペアプロ|スクラム|スプリント|カンバン|タスク管理/iu;
/** 事実のように見える数字・出来事・固有の名前 */
const FACT = /\d+\s*(%|％|人|万|億|円|ドル|件|社|年|月|日)|発表|調査によると|によれば|リリースした|株式会社|Inc\.|\bLtd\b/iu;

/**
 * 瓦版の話題として気になる所（1件ずつ `quest.news[i]: 理由`）。地図の形の検査（E_FORMAT）は engine の validateMap がする。
 * product: 作っている製品の説明（願い・題・pitch）。開発の道具を作っているときは、開発の言葉を気にしない。
 */
export function newsProblems(news, product = '') {
  if (!Array.isArray(news)) return [];
  const devTool = PROCESS.test(product) || /開発|エンジニア|プログラ|コード|Git|テスト/iu.test(product);
  const problems = [];
  news.forEach((text, index) => {
    if (typeof text !== 'string') return;
    if (!devTool && PROCESS.test(text)) problems.push(`quest.news[${index}]: 開発の進め方のコツに見えます。作っている製品の分野の話題にしてください（「${text}」）`);
    if (FACT.test(text)) problems.push(`quest.news[${index}]: 数字・出来事・会社名のような、事実に見える書き方があります。一般的な言い方にしてください（「${text}」）`);
  });
  return problems;
}
